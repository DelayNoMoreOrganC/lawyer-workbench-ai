# 获取法律系统提示词的函数
def get_legal_system_prompt(task_type: str) -> str:
    """
    根据任务类型获取对应的系统提示词

    Args:
        task_type: 任务类型 (legal_analysis, document_generation, case_analysis,
                   evidence_evaluation, legal_consultation, mediation)

    Returns:
        对应的系统提示词
    """
    prompts = {
        "legal_analysis": LEGAL_ANALYSIS_SYSTEM,
        "document_generation": DOCUMENT_GENERATION_SYSTEM,
        "case_analysis": CASE_ANALYSIS_SYSTEM,
        "evidence_evaluation": EVIDENCE_EVALUATION_SYSTEM,
        "legal_consultation": LEGAL_CONSULTATION_SYSTEM,
        "mediation": MEDIATION_SYSTEM,
        "chat": LEGAL_CONSULTATION_SYSTEM  # 默认使用法律咨询
    }

    return prompts.get(task_type, LEGAL_CONSULTATION_SYSTEM)


# 构建法律咨询的用户消息
def build_legal_user_prompt(user_input: str, context: dict = None) -> str:
    """
    构建法律咨询的用户消息

    Args:
        user_input: 用户输入
        context: 上下文信息（如案件信息、当事人信息等）

    Returns:
        构建好的用户消息
    """
    prompt = f"用户咨询：{user_input}\n"

    if context:
        prompt += "\n相关背景信息：\n"
        for key, value in context.items():
            prompt += f"- {key}：{value}\n"

    return prompt


# 构建案件分析的用户消息
def build_case_analysis_prompt(case_info: dict) -> str:
    """
    构建案件分析的用户消息

    Args:
        case_info: 案件信息字典

    Returns:
        构建好的案件分析消息
    """
    prompt = "请对以下案件进行详细分析：\n\n"

    prompt += f"案件名称：{case_info.get('case_name', '未知')}\n"
    prompt += f"案件类型：{case_info.get('case_type', '未知')}\n"
    prompt += f"案件状态：{case_info.get('case_status', '未知')}\n"
    prompt += f"案件标的：{case_info.get('case_amount', 0)}元\n"
    prompt += f"审理法院：{case_info.get('court_name', '未知')}\n"

    if case_info.get('case_brief'):
        prompt += f"案件简介：{case_info['case_brief']}\n"

    if case_info.get('plaintiff'):
        prompt += f"原告信息：{case_info['plaintiff']}\n"

    if case_info.get('defendant'):
        prompt += f"被告信息：{case_info['defendant']}\n"

    prompt += "\n请按照以下维度进行分析：\n"
    prompt += "1. 事实认定与法律关系分析\n"
    prompt += "2. 适用法律法规\n"
    prompt += "3. 争议焦点识别\n"
    prompt += "4. 证据充分性评估\n"
    prompt += "5. 法律风险分析\n"
    prompt += "6. 诉讼策略建议\n"
    prompt += "7. 胜诉可能性评估\n"

    return prompt


# 构建文书生成的用户消息
def build_document_generation_prompt(doc_type: str, case_info: dict) -> str:
    """
    构建文书生成的用户消息

    Args:
        doc_type: 文书类型
        case_info: 案件信息

    Returns:
        构建好的文书生成消息
    """
    prompt = f"请根据以下信息生成一份标准的{doc_type}：\n\n"

    for key, value in case_info.items():
        if value:  # 只包含非空字段
            prompt += f"{key}：{value}\n"

    prompt += f"\n要求：\n"
    prompt += "1. 格式规范，符合{doc_type}的法定格式\n"
    prompt += "2. 语言精确，表述严谨\n"
    prompt += "3. 逻辑清晰，论证充分\n"
    prompt += "4. 内容完整，包含必要条款\n"
    prompt += "5. 提醒用户核实相关信息并咨询专业律师\n"

    return prompt